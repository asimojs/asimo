
export function addNumbers(a: number, b: number) {
    return a + b;
}

export function subtractNumbers(a: number, b: number) {
    return a - b;
}

export function multiplyNumbers(a: number, b: number) {
    return a * b;
}

export function divideNumbers(a: number, b: number) {
    return a / b;
}